// Video Projects / Campaign / Paid / Lifecycle hiring-facing regression.
"use strict";
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const assert=require("node:assert/strict");
const {JSDOM,VirtualConsole}=require("jsdom");

(async()=>{
  const site=path.resolve(__dirname,"../site");
  const p=fs.readFileSync(path.join(site,"projects.js"),"utf8");
  const css=fs.readFileSync(path.join(site,"growth.css"),"utf8");
  new vm.Script(p,{filename:"site/projects.js"});
  assert.ok(css.includes("/* Video Projects: integrated Brand, Campaign, Paid creative and Lifecycle narrative */"),"Video integration styles are absent");
  assert.ok(css.includes(".video-handoff-map"),"Lifecycle responsive layout missing");
  const html=fs.readFileSync(path.join(site,"index.html"),"utf8").replace(/<script[^>]*src[^>]*><\/script>/g,"");
  const errors=[];
  const dom=new JSDOM(html,{url:"https://portfolio.test/",runScripts:"outside-only",pretendToBeVisual:true,virtualConsole:new VirtualConsole()});
  const w=dom.window,d=w.document;w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
  w.addEventListener("error",e=>errors.push(e.message));
  for(const file of ["data.js","selected-work.js","growth.js","projects.js","app.js","role-journeys.js"])
    w.eval(fs.readFileSync(path.join(site,file),"utf8"));
  const route=async(r)=>{w.location.hash="#/"+r;await new Promise(resolve=>setTimeout(resolve,110));};
  await route("case/creative/video-projects");
  const root=d.getElementById("video-projects");
  assert.ok(root,"Video Projects route missing");
  const count=(q)=>root.querySelectorAll(q).length;
  assert.equal(count(".tvc-work-grid .tvc-work-card"),2,"Preserve two seasonal TVC works");
  assert.equal(count("#kol-shorts video"),2,"Preserve two independent Creator clips");
  assert.equal(count("#video-insight-choices .video-insight-grid article"),3,"Market/customer/brand creative choices incomplete");
  assert.equal(count("#video-campaign-strategy .tvc-campaign-bridge-grid article"),3,"Three evidence-specific formats required");
  assert.equal(count("#video-awareness-to-lifecycle .video-stage-grid article"),5,"Brand to lifecycle content sequence incomplete");
  assert.equal(count("#video-paid-architecture .video-paid-family-grid article"),3,"Three Paid creative families required");
  assert.equal(count("#video-paid-architecture .video-test-logic>div"),3,"Paid creative test and measurement handoff missing");
  assert.equal(count("#video-paid-to-lifecycle .video-handoff-map article"),4,"Social/Paid through CRM and Loyalty handoff incomplete");
  assert.equal(count("#video-production-process .video-production-steps article"),4,"Video production and approvals incomplete");
  assert.equal(count("#video-insight-choices .video-insight-grid small"),3,"Creative choices must retain market/customer/brand lenses");
  assert.ok(root.textContent.includes("Power Every Move"),"Brand promise absent");
  assert.ok(root.textContent.includes("Make Room for What Matters")===false,"Seasonal TVCs must not be falsely labeled as M3 Campaign outputs");
  assert.ok(root.textContent.includes("不是已经完成付费投放")===false,"Avoid generic unsupported campaign completion statements");
  assert.ok(root.textContent.includes("不虚构广告上线、CPA、ROAS"),"Paid metrics must not be invented");
  assert.ok(root.textContent.includes("视频接触不等于购买意愿"),"Video reach must not become purchase-intent evidence");
  assert.ok(root.textContent.includes("积分、VIP、推荐奖励"),"Loyalty boundary missing");
  assert.ok(root.querySelector('a[href="#/case/gtm/campaign-architecture"]'),"Cross-case Campaign link missing");
  assert.ok(root.querySelector('a[href="#/case/crm/crm-handoff"]'),"Lifecycle link missing");
  assert.ok(root.querySelector('a[href="#/case/brand/brand-positioning"]'),"Brand link missing");
  assert.ok(root.querySelector('a[href="#/case/creator"]'),"Creator link missing");
  assert.ok(root.querySelector('#creative-production-scope'),"Existing production deep link missing");
  const videos=[...root.querySelectorAll("#kol-shorts video source")].map(x=>x.getAttribute("src")).sort();
  assert.deepEqual(videos,["assets/video/creator-livingroom-7s.mp4","assets/video/creator-staircase-7s.mp4"].sort());
  assert.ok(root.querySelector('#thanksgiving-tvc iframe[src*="1xuDMGJbNw4RZt9nBuyLkjy7Hl6MZZm6y"]'),"Thanksgiving TVC missing");
  assert.ok(root.querySelector('#holiday-full-film iframe[src*="15m5TOYZh90NUqTmSbHget8BJbeBEhLKE"]'),"Christmas TVC missing");
  await route("case/gtm/campaign-architecture");
  const camp=d.getElementById("campaign-architecture");
  assert.ok(camp&&camp.querySelectorAll("#campaign-video-production-link .campaign-video-steps span").length===4,"Campaign to video production handoff incomplete");
  assert.ok(camp.querySelector('#campaign-video-production-link a[href="#/case/creative/video-projects"]'),"Campaign must link to original Video Projects");
  assert.equal(errors.length,0,"Page errors: "+errors.join(" | "));
  dom.window.close();
  console.log("PASS: 2 TVCs / 2 Creator clips / 3 creative briefs / 5 content stages / 3 Paid families / 4 Lifecycle handoffs / 4 production steps / Campaign cross-link");
})().catch(e=>{console.error(e);process.exitCode=1});
